type previewHeading struct {
	ID    string
	Text  string
	Level int
}
type previewArticleData struct {
	Title           string
	Description     string
	Stylesheet      string
	Body            template.HTML
	Summary         string
	Category        string
	CategoryURL     string
	CoverURL        string
	Author          *ArticleAuthorOut
	AuthorCount     int
	AuthorAvatarURL string
	Published       string
	PublishedISO    string
	ReadingTime     int
	CharCount       int
	Headings        []previewHeading
}

