func (m *Module) renderArticlePreview(ctx *app.Ctx, article *Article, draft ArticleRevisionContent) (string, error) {
	rendered, stats, err := markdown.Render(draft.BodyMD, m.svc.siteURL, nil)
	if err != nil {
		return "", err
	}
	anchored, headings := markdown.AnchorHeadings(rendered)
	data := previewArticleData{
		Title: draft.Title, Description: draft.SearchDescription, Summary: draft.Summary,
		Stylesheet: m.previewStylesheet, CategoryURL: "/news/", Category: "未选分类",
		Headings: []previewHeading{},
	}
	if strings.TrimSpace(data.Title) == "" {
		data.Title = "（无标题）"
	}
	if data.Description == "" {
		data.Description = draft.Summary
	}
	if len(headings) >= 3 {
		rendered = anchored
		for _, heading := range headings {
			data.Headings = append(data.Headings, previewHeading{ID: heading.Anchor, Text: heading.Text, Level: heading.Level})
		}
	}
	// The only trusted HTML is generated by the common Markdown sanitizer.
	data.Body = template.HTML(rendered)
	plain := markdown.PlainHTML(rendered)
	data.CharCount = markdown.WordCount(plain)
	data.ReadingTime = markdown.ReadingMinutes(data.CharCount, stats.Images, stats.Videos)
	if draft.CategoryID != nil {
		category, err := m.svc.store.GetCategoryByID(ctx.Context, *draft.CategoryID)
		if err != nil {
			return "", err
		}
		if category != nil {
			data.Category = category.Name
			if category.Slug != "" {
				data.CategoryURL = "/news/?category=" + url.QueryEscape(category.Slug)
			}
		}
	}
	cover := draft.CoverImageID
	if cover == nil {
		pool, err := media.LoadPool(ctx.Context, m.svc.store.d.ReadPool(), "default_cover")
		if err != nil {
			return "", err
		}
		cover = media.PickCover(pool, article.ID, 0)
	}
	if cover != nil {
		data.CoverURL = fmt.Sprintf("/media/r/%d/fill-2400x1200.webp", *cover)
	}
	data.Author, err = m.svc.store.articleAuthor(ctx.Context, draft.AuthorID)
	if err != nil {
		return "", err
	}
	if data.Author != nil {
		data.AuthorCount, err = m.svc.store.authorPublicArticleCount(ctx.Context, data.Author.UserID)
		if err != nil {
			return "", err
		}
		if data.Author.IsActive && data.Author.AvatarImageID != nil {
			data.AuthorAvatarURL = fmt.Sprintf("/media/r/%d/fill-88x88.webp", *data.Author.AvatarImageID)
		}
	}
	if article.FirstPublishedAt != nil {
		zone := time.FixedZone("Asia/Shanghai", 8*60*60)
		data.Published = article.FirstPublishedAt.In(zone).Format("2006.01.02")
		data.PublishedISO = article.FirstPublishedAt.In(zone).Format(time.RFC3339)
	}
	var result bytes.Buffer
	if err := articlePreviewTemplate.Execute(&result, data); err != nil {
		return "", err
	}
	return result.String(), nil
}
